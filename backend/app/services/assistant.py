"""
Assistant service — the only place that combines field data and the AI.

PIPELINE
--------
question → recompute field analyses → structured context → LLM (optional)
        → rule-based fallback → persist conversation → response

The service never lets the model calculate a number. It recomputes every analysis
from the same deterministic services used by the dashboard, so an answer can
never reference a value that the UI would not show.

PERSISTENCE
-----------
* User and assistant messages are stored (useful for follow-ups and auditing).
* The full context JSON is stored only on the assistant message. It is also
  returned in `ChatResponse.context_used` so the user can inspect exactly what
  the model saw.
"""

import logging

from sqlalchemy.orm import Session

from app.ai import explainer, provider
from app.ai.context import build_field_context
from app.ai.rate_limit import limiter
from app.config import get_settings
from app.db import repository
from app.db.models import Field
from app.schemas.assistant import ChatRequest, ChatResponse
from app.services import crop_health
from app.services import environment as environment_service
from app.services import irrigation as irrigation_service
from app.services import plant_images as plant_images_service
from app.services import vegetation as vegetation_service

logger = logging.getLogger(__name__)

NOTICE_LLM = (
    "Explanation generated by the configured AI model using only the computed field "
    "context shown below. The model cannot create or change measurements."
)
NOTICE_NOT_CONFIGURED = (
    "No AI model is configured (set AI_API_KEY). This answer was generated by the "
    "deterministic rule-based explainer from the same computed data."
)
NOTICE_PROVIDER_FAILED = (
    "The AI provider was unavailable, so this answer was generated by the "
    "deterministic rule-based explainer from the same computed data."
)
NOTICE_RATE_LIMITED = (
    "The AI request limit for this hour was reached. This answer was generated by the "
    "deterministic rule-based explainer instead."
)
NOTICE_DEMO = (
    "Demo mode: the analyses describe the cached NASA POWER snapshot for Qena, Egypt "
    "(2025-11-01 to 2026-03-10), not live data or necessarily this field."
)


async def chat(
    session: Session,
    *,
    field: Field,
    payload: ChatRequest,
    client_key: str,
) -> ChatResponse:
    """Compute fresh analyses, build grounded context and answer the question."""
    settings = get_settings()
    mode = payload.mode or settings.data_mode

    # 1) Recompute the same analyses the dashboard shows. NASA requests are
    #    served from the in-process TTL cache, so this stays inexpensive.
    environment, _processed, series = environment_service.build_environment(
        session, field=field, mode=mode
    )
    irrigation = irrigation_service.analyze_irrigation(session, field=field, mode=mode)
    vegetation = vegetation_service.get_vegetation(session, field=field, mode=mode)
    health = crop_health.analyze_health(session, field=field, mode=mode)

    # Demo analyses use the snapshot's planting date; every other mode uses the
    # user's field profile. The context records which date was used.
    analysis_planting = (
        series.demo.planting_date
        if series.is_demo and series.demo is not None
        else field.planting_date
    )

    # 2) Build the single, auditable data object passed to the model.
    context = build_field_context(
        field=field,
        environment=environment,
        irrigation=irrigation,
        health=health,
        vegetation=vegetation,
        analysis_planting_date=analysis_planting,
        environment_latitude=series.latitude,
        environment_longitude=series.longitude,
        plant_images=plant_images_service.context_block(session, field),
    )

    # 3) Resolve the conversation before adding the new user message so the
    #    model only receives prior turns as history.
    conversation = repository.get_or_create_conversation(
        session, field=field, conversation_id=payload.conversation_id, first_message=payload.message
    )
    prior = repository.messages_for_conversation(session, conversation.id, limit=6)
    history = [{"role": message.role, "content": message.content} for message in prior]
    repository.add_message(
        session, conversation=conversation, role="user", content=payload.message
    )

    # 4) Try the LLM when configured and within the rate limit; always fall back
    #    to the deterministic explainer rather than failing the request.
    reply: str | None = None
    provider_name = "rule_based"
    fallback_reason = ""

    if not settings.ai_configured:
        fallback_reason = "not_configured"
    elif not limiter.allow(client_key, settings.ai_max_requests_per_hour):
        fallback_reason = "rate_limited"
    else:
        try:
            reply = await provider.generate_reply(
                question=payload.message, context=context, history=history, settings=settings
            )
            provider_name = "llm"
        except provider.LlmUnavailable as exc:
            logger.info("AI fallback: %s", exc)
            fallback_reason = "provider_failed"

    if reply is None:
        reply = explainer.answer_question(payload.message, context)

    notice = {
        "": NOTICE_LLM,
        "not_configured": NOTICE_NOT_CONFIGURED,
        "provider_failed": NOTICE_PROVIDER_FAILED,
        "rate_limited": NOTICE_RATE_LIMITED,
    }[fallback_reason]
    if environment.is_demo:
        notice = f"{notice} {NOTICE_DEMO}"

    # 5) Persist the answer together with the exact context used.
    repository.add_message(
        session,
        conversation=conversation,
        role="assistant",
        content=reply,
        provider=provider_name,
        context=context,
    )

    return ChatResponse(
        reply=reply,
        provider=provider_name,
        conversation_id=conversation.id,
        context_used=context,
        notice=notice,
        is_demo=environment.is_demo,
    )
